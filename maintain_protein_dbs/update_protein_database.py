def protein_in_directory(prot, pdir):
    # test presence in regular directory
    pfull_dir = f"{pdir}/{prot[0]}/{prot[1]}"
    p_name = f"generated-{prot}-"
    if os.path.isdir(pfull_dir):
        for gdir in os.listdir(pfull_dir):
            if gdir.startswith(p_name):
                return True

    # test presence in "missing_ligand_file" directory
    # this could not be generated until we have new ligand files
    pfull_dir = f"{pdir}/missing_ligand_file"
    p_name = f"generated-{prot}-"
    if os.path.isdir(pfull_dir):
        for gdir in os.listdir(pfull_dir):
            if gdir.startswith(p_name):
                return True

    return False


def protein_on_web(link):
    ret = utils_common.curl_exists_file(link)
    if ret == "302" or ret == "200":
        return True
    else:
        return False


def maintain_missing_protein(args, protein, fd):
    fd.write(f"{protein}\n")
    if (args.download_pdb_cif):
        cif_file_name = f"{args.download_pdb_cif}/{protein}.cif"
        if not os.path.exists(cif_file_name):
            utils_pdbe_api.download_protein_cif(args.download_pdb_cif, protein)
            print( protein, "downloaded")
        else:
            print(f"{cif_file_name} already exists")


