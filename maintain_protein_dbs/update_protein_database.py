def read_cath_protein_list():
    timestamp = time.strftime("%Y-%m-%d")
    filename = f"pdb_entry_type_{timestamp}.txt"
    p_list = []
    ret = True
    if not os.path.exists(filename):
        link = "https://ftp.wwpdb.org/pub/pdb/derived_data/pdb_entry_type.txt"
        link = "https://files.rcsb.org/pub/pdb/derived_data/pdb_entry_type.txt"
        directory = ""
        filename = f"pdb_entry_type_{timestamp}.txt"
        ret = utils_common.curl_file(link, directory, filename, False, "")
    if ret:
        with open(filename, "r") as fd:
            line = fd.readline()
            s = line.split("\t")
            while line:
                if s[1].startswith("prot"):
                    p_list.append(s[0])
                line = fd.readline()
                s = line.split("\t")
    return p_list


